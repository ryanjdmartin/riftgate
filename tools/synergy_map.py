class Map:
    def __init__(self):
        self.sets = defaultdict(list)    # currency -> [entry]
        self.reads = defaultdict(list)
        self.unmapped = []
        self.co = load("components")["entries"]
        self.ch = load("chassis")["entries"]
        self.mo = load("modules")["entries"]
        self.fo = load("foes")["entries"]
        self.locked_on = {}
        for c in self.ch:
            for cid in c.get("fixed", []):
                if c["name"] not in self.locked_on.setdefault(cid, []):
                    self.locked_on[cid].append(c["name"])
        self.stocked_on = {}
        for c in self.ch:
            for cid in c.get("loadout", []):
                self.stocked_on.setdefault(cid, []).append(c["name"])
        self.tags = defaultdict(lambda: {"slottable": [], "locked": []})
        self.heat_guns = 0

    # ---- entries, each a dict {who, kind, tier, chassis, maker, planned}
    def piece(self, e):
        locked = "tier" not in e
        return {"who": e["name"], "kind": "locked" if locked else "slottable", "tier": e.get("tier"),
                "on": self.locked_on.get(e["id"], []), "maker": e.get("maker", ""), "planned": e.get("status") == "planned",
                "stocked": self.stocked_on.get(e["id"], [])}

    def add(self, cur, how, entry):
        if cur is None:
            return
        if cur not in CURRENCIES:
            self.unmapped.append("%s -> %s" % (entry["who"], cur))
            return
        (self.sets if how == "sets" else self.reads)[cur].append(entry)

    def walk(self):
        for e in self.co:
            f = e.get("face", {})
            p = self.piece(e)
            for t in e.get("tags", []):
                self.tags[t]["locked" if p["kind"] == "locked" else "slottable"].append(e["name"])
            for kw in f.get("keywords", []):
                if kw not in KEYWORDS:
                    self.unmapped.append("%s: keyword %s" % (e["name"], kw))
                for cur, how in KEYWORDS.get(kw, []):
                    if kw in ("cleave", "penetrate", "splash"):
                        self.add(cur, how, dict(p, area="%s %s" % ({"cleave": "Spread"}.get(kw, kw.capitalize()), f.get(kw, "a debuff's, no number"))))
                    else:
                        self.add(cur, how, p)
            for k, v in f.items():
                if k in ("kind", "reach", "power", "keywords", "heat", "targets", "status", "stacks", "rounds",
                         "burn", "flak", "cryo", "cleave", "penetrate", "splash", "gates", "consumes", "per_consumed", "per_heat", "per_missing", "power_per_load"):
                    continue
                if k not in FACE_FIELDS:
                    self.unmapped.append("%s: face field %s" % (e["name"], k))
                for cur, how in FACE_FIELDS.get(k, []):
                    self.add(cur, how, p)
            if f.get("kind") == "buff":
                self.add(f.get("status"), "sets", p)
            charged = f.get("charged") or {}
            if charged.get("status"):
                self.add(charged["status"], "sets", dict(p, how="charged"))
            for kw in charged.get("keywords", []):
                for cur, how in KEYWORDS.get(kw, []):
                    self.add(cur, how, dict(p, how="charged"))
            if f.get("kind") == "shield" and f.get("targets", "self_ally") != "self":
                self.add("shield_granted", "sets", p)
            if f.get("kind") == "vent" and f.get("targets", "self_ally") != "self":
                self.add("ally_heat", "reads", p)
            if int(f.get("heat", 0) or 0) > 0 and f.get("kind") == "attack":
                self.heat_guns += 1
            for status in (f.get("gates") or {}).values():
                self.add(status.get("status"), "reads", dict(p, how="gated on it"))
            if f.get("consumes"):
                self.add(f["consumes"], "reads", dict(p, how="consumes it"))
            if int(f.get("strikes", 1) or 1) > 1 or f.get("reach") == "sweep" or f.get("spends_magazine"):
                self.add("flakked", "reads", dict(p, how="strikes"))
                self.add("overcharged", "reads", dict(p, how="strikes"))
                self.add("primed", "reads", dict(p, how="strikes"))
            if f.get("kind") == "attack" and int(f.get("power", 0) or 0) >= 5 and not f.get("strikes"):
                self.add("shocked", "reads", dict(p, how="a big blow"))
        for c in self.ch:
            p = {"who": c["name"] + "'s " + str((c.get("passive") or {}).get("name", "passive")), "kind": "passive", "tier": c.get("tier"),
                 "on": [], "maker": c.get("maker", ""), "planned": (c.get("passive") or {}).get("status") == "planned", "stocked": []}
            self.walk_effects((c.get("passive") or {}).get("effects", []), p)
            if (c.get("passive") or {}).get("status") == "planned":
                self.add("heat", "reads", dict(p, how="planned"))   # the Storm Petrel's shield in place of heat
        for m in self.mo:
            p = {"who": m["name"], "kind": "module", "tier": m.get("tier"), "on": [], "maker": m.get("maker", ""),
                 "planned": (m.get("text") or {}).get("status") == "planned", "stocked": []}
            self.walk_effects(((m.get("text") or {}).get("effects") or []), p)
        for f in self.fo:
            if not f.get("name"):
                continue
            p = {"who": f["name"], "kind": "foe", "tier": None, "on": [], "maker": "", "planned": False, "stocked": []}
            for a in f.get("actions", []):
                for kw in a.get("keywords", []):
                    if kw in FOE_RIDERS:
                        self.add(FOE_RIDERS[kw], "sets", dict(p, who="%s's %s" % (f["name"], a["name"])))
                if a.get("effect") in FOE_EFFECTS:
                    self.add(FOE_EFFECTS[a["effect"]], "sets", dict(p, who="%s's %s" % (f["name"], a["name"])))

    def walk_effects(self, effects, p):
        for eff in effects:
            name = str(eff.get("effect", ""))
            trig = str(eff.get("trigger", ""))
            if name not in EFFECTS:
                self.unmapped.append("%s: effect %s" % (p["who"], name))
            for cur, how in EFFECTS.get(name, []):
                self.add(cur, how, p)
            if trig not in TRIGGERS:
                self.unmapped.append("%s: trigger %s" % (p["who"], trig))
            tcur = TRIGGERS.get(trig)
            if tcur == "paradox_feed":
                for cur in ("burning", "flakked", "shocked", "exposure", "cryoed", "suppressed", "webbed", "vitriol", "mine"):
                    self.add(cur, "reads", dict(p, how="counts it"))
            elif tcur:
                self.add(tcur, "reads", p)
            when = eff.get("when")
            if when and when not in CONDITIONS:
                self.unmapped.append("%s: condition %s" % (p["who"], when))
            if when == "target_status":
                if eff.get("status"):
                    self.add(eff["status"], "reads", p)
                else:
                    for cur in ("burning", "flakked", "shocked", "exposure", "cryoed", "suppressed", "webbed", "vitriol", "mine", "paradox"):
                        self.add(cur, "reads", dict(p, how="any status"))
            if when == "attacker_status":
                self.add(eff.get("status"), "reads", p)
            if CONDITIONS.get(when):
                self.add(CONDITIONS[when], "reads", p)
            if name == "stack_status":
                self.add(str(eff.get("value")), "sets", p)
            if name == "lay_status":
                self.add(str(eff.get("value")), "sets", p)
            if name == "grant_keyword":
                for cur, how in KEYWORDS.get(str(eff.get("value")), []):
                    self.add(cur, how, p)
            if name == "add_shield" and trig in ("on_hull_damage", "on_heat_gain"):
                pass   # the trigger's read is the synergy; the shield is its payoff
            if name == "keep_status":
                self.add(str(eff.get("value")), "reads", dict(p, how="keeps it"))
            if name == "add_stacks":
                self.add("heat", "reads", dict(p, how="deepens every stack by it"))
            if name == "rewrite_weapon":
                self.add("rank", "reads", p)
            if name == "multiply_printed":
                self.add("heat", "sets", p)
            if name in ("add_damage", "multiply_damage") and when is None and trig == "on_attack" and p["kind"] == "module":
                pass


def word(entry):
    s = entry["who"]
    if entry.get("area"):
        s += " (%s)" % entry["area"]
    if entry["kind"] == "slottable":
        s += " (tier %s)" % entry["tier"]
        if entry.get("stocked"):
            s += ", stocked"
    elif entry["kind"] == "locked":
        s += " (locked, %s)" % ", ".join(entry["on"] or ["nobody"])
    elif entry["kind"] == "module":
        s += " (module, tier %s)" % entry["tier"]
    elif entry["kind"] == "foe":
        s += " (foe)"
    if entry.get("how"):
        s += ": " + entry["how"]
    if entry.get("planned"):
        s += " [planned]"
    return s


def dedupe(entries):
    seen = []
    out = []
    for e in entries:
        key = (e["who"], e.get("how"))
        if key in seen:
            continue
        seen.append(key)
        out.append(e)
    return out


def render(m):
    L = []
    L.append("| Currency | Side | Set by | Read by |")
    L.append("|---|---|---|---|")
    holes = []
    unique = []
    for cur, (label, side) in CURRENCIES.items():
        if cur == "tags":
            continue
        setters = dedupe(m.sets.get(cur, []))
        readers = dedupe(m.reads.get(cur, []))
        engine = ENGINE_READERS.get(cur, [])
        sl = [e for e in setters if e["kind"] == "slottable" and not e.get("planned")]
        set_text = "; ".join(word(e) for e in setters) or "nothing"
        if cur == "heat":
            set_text = "every weapon with heat (%d pieces); " % m.heat_guns + set_text
        L.append("| %s | %s | %s | %s |" % (label, side, set_text, "; ".join(engine + [word(e) for e in readers]) or "nothing"))
        foe_laid = cur in ("scorched", "disabled", "corrupted", "burning_mech", "hot_streak")
        if (side == "on a foe" or side == "on a machine") and not foe_laid:
            if setters and not sl:
                unique.append(label)
            if len(sl) == 1:
                holes.append("**%s** has one slottable setter, %s." % (label, word(sl[0])))
            if not readers and cur not in ("suppressed", "webbed", "disrupt", "swap", "phased", "barrier", "ward", "sealed", "regenerating",
                                           "rallied", "spun_up", "braced", "vitriol", "mine", "paradox", "lure", "retaliate"):
                holes.append("**%s** is read by nothing but its own effect." % label)
    L.append("")
    L.append("Tags, by the slottable pieces that wear them (locked in brackets); nothing but the screen's lunge reads one:")
    L.append("")
    L.append("| Tag | Slottable | Locked |")
    L.append("|---|---|---|")
    for t in ["ballistic", "missile", "beam", "plasma", "flame", "arc", "blade", "melee"]:
        d = m.tags.get(t, {"slottable": [], "locked": []})
        L.append("| %s | %d: %s | %d: %s |" % (t.capitalize(), len(d["slottable"]), ", ".join(d["slottable"]) or "none",
                                              len(d["locked"]), ", ".join(d["locked"]) or "none"))
    L.append("")
    L.append("What the map computes (what it means is the section after the map):")
    L.append("")
    L.append("- Unique to a chassis (set by locked pieces and passives alone, so a build reaches it only by fielding that machine): %s." % ", ".join(unique))
    for h in holes:
        L.append("- " + h)
    if m.unmapped:
        L.append("")
        L.append("Unmapped by this script (add the word to its tables): " + "; ".join(sorted(set(m.unmapped))))
    return "\n".join(L)


def main():
    m = Map()
    m.walk()
    text = render(m)
    if "--write" in sys.argv:
        if not PROPOSAL.exists():
            raise SystemExit("no %s to write into" % PROPOSAL)
        s = PROPOSAL.read_text(encoding="utf-8")
        if START not in s or END not in s:
            raise SystemExit("the proposal carries no synergy-map markers")
        head, rest = s.split(START, 1)
        _, tail = rest.split(END, 1)
        PROPOSAL.write_text(head + START + "\n" + text + "\n" + END + tail, encoding="utf-8")
        print("wrote the synergy map into %s" % PROPOSAL.relative_to(ROOT))
    else:
        print(text)


