"""The bible's vocabulary tables, generated from content (Ryan, 16 October: a table of buffs
and debuffs, and one of keywords with their usage counts, both maintained in the bible). Run
from the repo root after any change to content/*.json, before the bible is republished:

    python3 tools/pages/bible_tables.py

It rewrites what stands between the two bible-tables markers in docs/design-bible.html and
leaves the rest of the file as it is.

A status's effect is its vocabulary codex, the text the player reads; its kind, where it
lands, how it stacks and how long it lasts are its vocabulary entry's design.table (the
# stacking word checked against the engine's policy on the status: add or renew). Who grants
it is counted from content through the engine's words below, and its reach follows: unique
when only chassis passives or locked components grant it, or on the foes' side when one foe
alone has the move; global otherwise. A keyword's counts are the components carrying it,
locked or not, the passives and modules granting it, and the foe moves carrying it; planned
entries are counted apart, in brackets. It warns about an engine status with no table row.
"""
import html
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
BIBLE = ROOT / "docs" / "design-bible.html"
START = "<!-- bible-tables:start (generated by tools/pages/bible_tables.py from content: edit the content and rerun, never these lines) -->"
END = "<!-- bible-tables:end -->"

# Who grants what, in the engine's own words (sim/skirmish.gd, sim/effects.gd), and the side it
# lands on. A keyword or effect missing here grants no status.
COMPONENT_KEYWORDS = {"ablate": [("ablating", "foe")], "shock": [("shocked", "foe")],
                      "suppress": [("suppressed", "foe"), ("numbed", "foe")],
                      "cryo": [("cryoed", "foe")], "brittle": [("brittled", "foe")], "expose": [("exposure", "foe")]}
FACE_FIELDS = {"braces": "braced", "fills_hopper": "hopper",
               "holds_all": "essence_flare"}   # the Quintessence Tap's hold on Empowered, a buff on its machine (Essence Flare, 15 November)
FACE_FIELDS_ON_FOES = {"webs": ["webbed", "suppressed", "numbed"]}   # the Web Bomb's own rule; the Syrinx Drone's status went with the slot mines (9 November), the Contractor's Expose is its keyword
PASSIVE_EFFECTS = {"seal_form": ("sealed", "machine"),
                   "paradox": ("paradox", "foe"), "muster": ("muster", "machine"),
                   "fill_hopper": ("hopper", "machine"), "hopper_plate": ("braced", "machine"),
                   "mine_on_spend": ("mine", "foe")}   # stack_status names its own, on the machine; the Reverberant Payload's Mine (9 November)
FOE_KEYWORDS = {"scorch": "scorched", "ablate": "ablating", "jam": "jammed", "corrupt": "corrupted", "brittle": "brittled", "expose": "exposure"}
FOE_EFFECTS_ON_MACHINES = {"ablate": "ablating", "scorch_all": "scorched", "corrupt_all": "corrupted",
                           "jam": "jammed", "swallow": "swallowed", "expose": "exposure"}
FOE_EFFECTS_ON_FOES = {"brace": "braced", "brace_all": "braced", "harden": "braced", "harden_all": "braced",
                       "rally": "kindled", "revive_once": "risen", "revive_once_ally": "risen",
                       "prime": "primed", "barrier": "barrier", "ward_all": "ward", "regenerate": "regenerating", "golden": "golden",
                       "appropriate": "appropriated", "phase": "phased"}   # the ladder's (28 October); golden the Thunder Ape's (4 November)
# A special that is a rider's own mechanic, played as a whole move, counts under the rider.
MOVE_AS_KEYWORD = {"ablate": "ablate", "jam": "jam", "scorch_all": "scorch", "corrupt_all": "corrupt", "swallow": "swallow", "merge": "merge", "dispel": "dispel", "golden": "golden_rage"}
VIA_STATUS = {"primed": [("ablating", "foe")], "paradox": [("suppressed", "foe"), ("numbed", "foe")]}
ENGINE_ALIASES = {"ablating_mech": "ablating", "brittled_mech": "brittled", "exposure_mech": "exposure",   # the same word on the other body
                  "phasing": "phased"}   # the wait for Phased, which is granted as the round ends (15 November)

# Printed rules, read off a component's face.
PRINTED = [("strikes", "Strikes", lambda f: int(f.get("strikes", 1)) > 1),
           ("vents_all", "Vents all", lambda f: bool(f.get("vents_all"))),
           ("power_per_missing", "Grows with missing HP", lambda f: int(f.get("power_per_missing", 0)) > 0),
           ("finisher", "Finisher", lambda f: int(f.get("finisher", 0) or 0) > 1),
           ("gated", "Gated", lambda f: bool(f.get("gates"))),
           ("consumes", "Consumes", lambda f: bool(f.get("consumes")) or bool(f.get("spends"))),   # a weapon's on its target, or equipment's of its own machine's count (the Quintessence Tap)
           ("self_ablate", "Ablates its firer", lambda f: int(f.get("self_ablate", 0) or 0) > 0),
           ("ignores_armour", "Ignores armour", lambda f: bool(f.get("ignores_armour"))),
           ("hopper_property", "The hopper", lambda f: int(f.get("fills_hopper", 0)) > 0 or int(f.get("fires_hopper", 0)) > 0),
           ("brace_property", "Braces", lambda f: int(f.get("braces", 0)) > 0),
           ("swap", "Swap", lambda f: bool(f.get("swaps"))),
           ("webbed", "Web Bomb", lambda f: bool(f.get("webs"))),   # the piece's own rule: the mark it leaves says it
           ("gather", "Gather", lambda f: bool(f.get("gathers_mines"))),
           ("detonate", "Detonate", lambda f: bool(f.get("detonates"))),
           # The Petrels' locked pieces (built 30 October).
           ("ally_action", "An ally's action", lambda f: bool(f.get("ally_action"))),
           ("rolls_target", "Rolls its die", lambda f: bool(f.get("rolls_target"))),
           ("kill_rerolls", "Rerolls a kill", lambda f: int(f.get("kill_rerolls", 0) or 0) > 0),
           ("team_rerolls", "Grants a reroll", lambda f: int(f.get("team_rerolls", 0) or 0) > 0),
           # A printed cooldown: the rounds an entry sits out after its spend (12 November); Rapid's own
           # switch-off is never printed.
           ("cooldown", "Cooldown", lambda f: "cooldown" in f)]
FOE_ONLY = ["scorch", "ablate", "jam", "corrupt", "brittle", "destroy", "drain", "dispel", "swallow", "merge", "golden_rage", "self_destruct", "all", "countdown", "grudge", "last_act", "parts"]
FOE_ONLY_TEXT = {"ablate": "Keyword with a number on a foe's attack: each blow that lands leaves that many stacks of Ablating on the machine it hits (Ablating, above).",
                 "brittle": "Keyword with a number on a foe's attack: each blow that lands leaves that many stacks of Brittle on the machine it hits (Brittle, above).",
                 "dispel": "A foe's move of its own, never a rider on a blow and never a last act's: Purge N, the rule ours runs, N stacks off every buff the machine it lands on carries, for good, whatever granted it; its Abilities and its stores stay; a Ward turns it away."}
SHARED = ["ablate", "brittle", "dispel"]   # our keyword and the foes' word share it, each with a row (Purge on both sides, 28 October; Brittle, 15 November)
KIND_ORDER = {"buff": 0, "debuff": 1, "ability": 2, "store": 3}   # a store is a capped resource, its own kind (Ryan, 21 October); an ability a unit's own mechanic, no buff or debuff (8 November)
ON_ORDER = {"machine": 0, "both": 1, "foe": 2}


def load(name):
    return json.loads((ROOT / "content" / name).read_text())


def esc(s):
    return html.escape(str(s), quote=False)


def the(name):
    """'the Drake', and 'the Thief' for a hero whose name already says The."""
    return "the " + (name[4:] if name.startswith("The ") else name)


def cell(pair):
    n, p = pair
    return ("%d" % n) + (" (+%d planned)" % p if p else "")


class Tally:
    def __init__(self):
        self.sources = {}    # status -> [{name, how, on, planned, foe, who}]
        self.keywords = {}   # keyword -> {unlocked, locked, passive, foe, moves: [n, planned], foes: set}

    def grant(self, status, on, name, how, planned=False, foe=None, who=None):
        self.sources.setdefault(status, []).append(
            {"name": name, "how": how, "on": on, "planned": planned, "foe": foe, "who": who or name})

    def count(self, key, column, planned, foe=None):
        row = self.keywords.setdefault(key, {"unlocked": [0, 0], "locked": [0, 0], "passive": [0, 0],
                                             "foe": [0, 0], "moves": [0, 0], "foes": set()})
        row[column][1 if planned else 0] += 1
        if foe and not planned:
            row["foes"].add(foe)
        return row


def tally(words):
    t = Tally()
    chassis = load("chassis.json")["entries"]
    fixed_on = {}
    for c in chassis:
        for cid in c.get("fixed", []):
            if c["name"] not in fixed_on.setdefault(cid, []):
                fixed_on[cid].append(c["name"])

    for c in load("components.json")["entries"]:
        f = c["face"]
        planned = c.get("status") == "planned"
        how = "locked" if c["id"] in fixed_on else "unlocked"
        machines = ", ".join(the(n) for n in fixed_on.get(c["id"], []))
        label = c["name"] + (" (%s's)" % machines if machines else "")
        who = machines or None
        for k in f.get("keywords") or []:
            t.count(k, how, planned)
            for status, on in COMPONENT_KEYWORDS.get(k, []):
                t.grant(status, on, label, how, planned, who=who)
        for key, _, test in PRINTED:
            if test(f):
                t.count(key, how, planned)
        if f.get("kind") == "buff" and f.get("status"):
            t.grant(f["status"], "machine", label, how, planned, who=who)
        for field, status in FACE_FIELDS.items():
            if f.get(field):
                t.grant(status, "machine", label, how, planned, who=who)
        for g in f.get("self_statuses") or []:   # what a spend lays on its own machine (the Hardlight Pulse's Hardened Light, 18 November)
            t.grant(g.get("status", ""), "machine", label, how, planned, who=who)
        for field, statuses in FACE_FIELDS_ON_FOES.items():
            if f.get(field):
                for status in statuses:
                    t.grant(status, "foe", label, how, planned, who=who)
        for eff in ((c.get("passive") or {}).get("effects") or []):
            if eff.get("effect") in PASSIVE_EFFECTS:
                status, on = PASSIVE_EFFECTS[eff["effect"]]
                t.grant(status, on, label, how, planned, who=who)
        # A charged form (the Swallowtail's locked pieces, spent for a muster) carries its own
        # keywords and statuses beside the plain form's.
        charged = f.get("charged") or {}
        if charged:
            clabel = c["name"] + " charged" + (" (%s's)" % machines if machines else "")
            for k in (charged.get("keywords") or []) + (["cleanse"] if charged.get("cleanse") else []):
                if k not in (f.get("keywords") or []):   # one count a piece, whichever form carries it
                    t.count(k, how, planned)
                for status, on in COMPONENT_KEYWORDS.get(k, []):
                    t.grant(status, on, clabel, how, planned, who=who)
            if charged.get("status"):
                t.grant(charged["status"], "machine", clabel, how, planned, who=who)

    def passive(p, label, how, who):
        planned = (p or {}).get("status", "implemented") != "implemented"
        counted = False
        for eff in ((p or {}).get("effects") or []):
            e = eff.get("effect")
            if eff.get("when") == "nth_shot" and not counted:   # a rule on every n-th shot keeps the count
                t.grant("shots", "machine", label, how, planned, who=who)
                counted = True
            if e == "one_of_each":   # two things a round marks the round's turn spent (the Needletail's relay)
                t.grant("quick_turned", "machine", label, how, planned, who=who)
            if e == "grant_keyword":
                t.count(str(eff.get("value")), "passive", planned)
            elif e == "stack_status":
                t.grant(str(eff.get("value")), "machine", label, how, planned, who=who)
            elif e == "lay_status":   # laid on each foe the blow hits (the funnel-web's Ambush)
                t.grant(str(eff.get("value")), "foe", label, how, planned, who=who)
            elif e == "self_status":   # laid on its own machine by a spend at a foe (an upgrade's branch)
                t.grant(str(eff.get("status")), "machine", label, how, planned, who=who)
            elif e in PASSIVE_EFFECTS:
                status, on = PASSIVE_EFFECTS[e]
                t.grant(status, on, label, how, planned, who=who)

    for c in chassis:
        p = c.get("passive") or {}
        passive(p, "%s's %s" % (the(c["name"]), p.get("name", "passive")), "passive", the(c["name"]))
        # Its upgrades' branches (the Storm Petrel's first, 17 November): each step a passive's worth
        # of effects on its locked piece, counted as a passive's are, the step named.
        for b in c.get("branches") or []:
            for i, step in enumerate(b.get("steps") or []):
                passive(step, "%s's %s %s" % (the(c["name"]), b.get("name", b.get("id", "")), "I" if i == 0 else "II"), "passive", the(c["name"]))
    for m in load("modules.json")["entries"]:
        if m.get("text"):
            passive(m["text"], "%s (module)" % m["name"], "module", None)

    raw = {e["id"]: e for e in load("foes.json")["entries"]}
    for foe in raw.values():
        name = foe.get("name", foe["id"])
        whom = the(name)
        if foe.get("promotes") in raw:
            # A promoted form keeps its hero's name (the content takes it as it loads); only its
            # own moves are its entry's, the rest counted on its hero.
            name = foe.get("name", raw[foe["promotes"]].get("name", foe["id"]))
            whom = "the promoted " + (name[4:] if name.startswith("The ") else name)
        for a in foe.get("actions", []):
            planned = a.get("status", "implemented") != "implemented"
            move = "%s's %s" % (whom, a.get("name", a.get("id")))
            for k in a.get("keywords") or []:
                t.count(k, "foe", planned, name)
                if k in FOE_KEYWORDS:
                    t.grant(FOE_KEYWORDS[k], "machine", move, "foe", planned, foe["id"], whom)
            # The move's own special and what it does also (16 November: a move is a short list
            # of steps), each effect counted where it lands.
            for e in [a.get("effect")] + [st.get("effect") for st in (a.get("before") or []) + (a.get("also") or [])]:
                if e in FOE_EFFECTS_ON_MACHINES:
                    t.grant(FOE_EFFECTS_ON_MACHINES[e], "machine", move, "foe", planned, foe["id"], whom)
                if e in FOE_EFFECTS_ON_FOES:
                    t.grant(FOE_EFFECTS_ON_FOES[e], "foe", move, "foe", planned, foe["id"], whom)
                if e in MOVE_AS_KEYWORD:
                    row = t.count(MOVE_AS_KEYWORD[e], "foe", planned, name)
                    row["moves"][1 if planned else 0] += 1
            if int(a.get("countdown", 0)) > 0:
                t.count("countdown", "foe", planned, name)
            if a.get("aloft"):
                t.grant("aloft", "foe", move, "foe", planned, foe["id"], whom)   # worn while the move gathers (the Roc's Stoop, 16 November)
            if int(a.get("per_kill", 0)) > 0:
                t.count("grudge", "foe", planned, name)
        if int(foe.get("rage", 0) or 0) > 0:
            t.grant("enraged", "foe", "%s's rage" % whom, "foe", False, foe["id"], whom)   # its own from the start (8 November)
        if foe.get("drains"):
            t.count("drain", "foe", False, name)   # its own Ability, on every blow (16 November); a rider until then
        if foe.get("parts"):
            t.grant("guarded", "foe", "%s's parts" % whom, "foe", False, foe["id"], whom)
            t.count("parts", "foe", False, name)
        if isinstance((foe.get("on_death") or {}).get("blow"), dict) or isinstance((foe.get("on_death") or {}).get("act"), dict):
            t.count("last_act", "foe", False, name)   # a fall: a blow, or one special in its place (16 November)
    for status, lays in VIA_STATUS.items():
        for target, on in lays:
            t.grant(target, on, "via %s" % words.get(status, {}).get("name", status), "via")
    return t


def reach(t, status, on):
    live = [s for s in t.sources.get(status, []) if s["on"] == on and not s["planned"] and s["how"] != "via"]
    if not live:
        return "planned" if any(s["on"] == on and s["planned"] for s in t.sources.get(status, [])) else None
    ours = [s for s in live if s["how"] != "foe"]
    theirs = [s for s in live if s["how"] == "foe"]
    out = []
    if ours:
        if any(s["how"] in ("unlocked", "module") for s in ours):
            out.append("global")
        else:
            out.append("unique: " + ", ".join(sorted({s["who"] for s in ours})))
    if theirs:
        out.append("global" if len({s["foe"] for s in theirs}) > 1 else "unique: " + theirs[0]["who"])
    return " / ".join(dict.fromkeys(out))


def granted_by(t, status):
    tags = {"unlocked": "", "locked": " (locked)", "passive": " (passive)", "module": "", "foe": "", "via": ""}
    rows = [s["name"] + tags[s["how"]] + (" (planned)" if s["planned"] else "") for s in t.sources.get(status, [])]
    return "; ".join(dict.fromkeys(rows)) or "nothing in content yet"


def status_rows(t, vocab):
    entries = [e for e in vocab if isinstance((e.get("design") or {}).get("table"), dict)]
    entries.sort(key=lambda e: (ON_ORDER.get(e["design"]["table"]["on"], 9),
                                KIND_ORDER.get(e["design"]["table"]["kind"], 9), e["name"]))
    rows = []
    for e in entries:
        tb = e["design"]["table"]
        sides = ["machine", "foe"] if tb["on"] == "both" else [tb["on"]]
        parts = []
        for on in sides:
            r = reach(t, e["id"], on)
            if r:
                parts.append(("on %ss: %s" % (on, r)) if tb["on"] == "both" else r)
        span = "; ".join(parts) or ("planned" if e.get("status") != "implemented" else "unused")
        name = e["name"] + (" (planned)" if e.get("status") != "implemented" else "")
        on_word = {"machine": "Machines", "foe": "Foes", "both": "Both"}[tb["on"]]
        rows.append("<tr><td>%s</td><td>%s</td><td>%s</td><td>%s</td><td>%s</td><td>%s</td><td>%s</td><td>%s</td></tr>" % (
            esc(name), esc(tb["kind"].capitalize()), on_word, esc(e["codex"]), esc(tb["stacks"]), esc(tb["lasts"]),
            esc(granted_by(t, e["id"])), esc(span[0].upper() + span[1:])))
    return entries, rows


def keyword_rows(t, vocab, words):
    empty = {"unlocked": [0, 0], "locked": [0, 0], "passive": [0, 0], "foe": [0, 0], "moves": [0, 0], "foes": set()}
    line = "<tr><td>%s</td><td>%s</td><td>%s</td><td>%s</td><td>%s</td><td>%s</td></tr>"
    rows = ['<tr><td colspan="6"><em>On our components</em></td></tr>']
    # Our Ablate and Purge share their words with the foes', which have rows of their own below.
    ours = [e for e in vocab if e["category"] == "keyword" and (e["id"] in SHARED or e["id"] not in FOE_ONLY)]
    for e in sorted(ours, key=lambda e: e["name"]):
        c = t.keywords.get(e["id"], empty)
        name = e["name"] + (" (planned)" if e.get("status") != "implemented" else "")
        rows.append(line % (esc(name), esc(e["codex"]), cell(c["unlocked"]), cell(c["locked"]), cell(c["passive"]), "&mdash;"))
    rows.append('<tr><td colspan="6"><em>Printed on our components (the star)</em></td></tr>')
    for key, label, _ in PRINTED:
        c = t.keywords.get(key, empty)
        rows.append(line % (esc(label), esc(words.get(key, {}).get("codex", "")), cell(c["unlocked"]), cell(c["locked"]), cell(c["passive"]), "&mdash;"))
    rows.append('<tr><td colspan="6"><em>On foe moves only</em></td></tr>')
    for key in FOE_ONLY:
        c = t.keywords.get(key, empty)
        word = words.get(key, {})
        name = {"ablate": "Ablate (a foe's)", "dispel": "Purge (a foe's)"}.get(key, word.get("name", key))
        if word.get("status", "implemented") != "implemented":
            name += " (planned)"
        who = ", ".join(sorted(the(n) for n in c["foes"]))
        note = cell(c["foe"]) + (" (%s)" % who if who else "")
        if c["moves"][0]:
            note += "; %d of them a move of its own" % c["moves"][0]
        rows.append(line % (esc(name), esc(FOE_ONLY_TEXT.get(key) or word.get("codex", "")), "&mdash;", "&mdash;", "&mdash;", esc(note)))
    return rows


def main():
    vocab = load("vocabulary.json")["entries"]
    words = {e["id"]: e for e in vocab}
    t = tally(words)
    entries, srows = status_rows(t, vocab)
    krows = keyword_rows(t, vocab, words)
    block = "\n".join([
        START,
        "  <h4>Buffs, debuffs and stores</h4>",
        '  <div class="tablewrap"><table><thead><tr><th>Status</th><th>Kind</th><th>On</th><th>Effect</th><th>Stacks</th><th>Lasts</th><th>Granted by</th><th>Global or unique</th></tr></thead><tbody>',
        *("  " + r for r in srows),
        "  </tbody></table></div>",
        "  <h4>Keywords</h4>",
        '  <div class="tablewrap"><table><thead><tr><th>Keyword</th><th>What it does</th><th>Unlocked components</th><th>Locked components</th><th>Passives and modules</th><th>Foe moves</th></tr></thead><tbody>',
        *("  " + r for r in krows),
        "  </tbody></table></div>",
        "  " + END,
    ])
    text = BIBLE.read_text()
    i, j = text.find(START), text.find(END)
    if i < 0 or j < 0:
        sys.exit("the bible has no bible-tables markers; put both where the tables go")
    BIBLE.write_text(text[:i] + block + text[j + len(END):])

    # An engine status with no table row is a status the tables miss.
    effects = (ROOT / "sim" / "effects.gd").read_text()
    engine = set(re.findall(r'^\t"([a-z_]+)": \{"id": "[a-z_]+", "name"', effects, re.M))
    for s in sorted({ENGINE_ALIASES.get(s, s) for s in engine} - {e["id"] for e in entries}):
        print("warning: the engine status '%s' has no design.table in content/vocabulary.json" % s, file=sys.stderr)
    # The table's stacking word against the engine's policy on the status (its "stacking":
    # add or renew; 17 October), so the table never says what the code does not do.
    policies = {}
    for sid, line in re.findall(r'^\t"([a-z_]+)": (\{"id": "[a-z_]+", "name".*)$', effects, re.M):
        found = re.search(r'"stacking": "([a-z]+)"', line)
        policies[sid] = found.group(1) if found else "add"
    words = {"Yes": ("add",), "No": ("renew",), "Never": ("renew",), "Renews": ("renew",)}
    aliases = {}
    for eng, voc in ENGINE_ALIASES.items():
        aliases.setdefault(voc, []).append(eng)
    for e in entries:
        word = e["design"]["table"]["stacks"].split(":")[0].strip()
        for sid in [e["id"]] + aliases.get(e["id"], []):
            if sid not in policies:
                continue
            if word not in words:
                print("warning: %s's stacks reads '%s'; a table's stacking word is Yes, No, Never or Renews" % (e["id"], word), file=sys.stderr)
            elif policies[sid] not in words[word]:
                print("warning: the table says %s stacks '%s' but the engine's policy on it is '%s'" % (e["id"], word, policies[sid]), file=sys.stderr)
    print("%d statuses and %d keyword rows written to %s" % (len(srows), len(krows), BIBLE.relative_to(ROOT)))


if __name__ == "__main__":
    main()
